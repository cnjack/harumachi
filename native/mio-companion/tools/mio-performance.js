export class EmotionMixer {
  constructor(profile){this.profile=profile;this.current={...profile.styles.neutral.face};this.vad=[0,0,0];this.restingMouth=0;this.last=null;}
  apply(base,expression,time,mouthOwned=true){
    const p=this.profile,e=expression||{style:'neutral'},target=p.styles[e.style];
    if(!target||!Object.hasOwn(p.intensities,e.intensity||'normal'))throw Error('Unknown expression');
    const gain=p.intensities[e.intensity||'normal'],neutral=p.styles.neutral.face;
    const reset=this.last===null||time<this.last,dt=Math.max(0,Math.min(.1,time-(this.last??time))),blend=reset?1:1-Math.exp(-dt/p.smoothingSeconds);this.last=time;
    for(const id of Object.keys(neutral)){const desired=neutral[id]+(target.face[id]-neutral[id])*gain;this.current[id]+=(desired-this.current[id])*blend;}
    this.vad=this.vad.map((v,i)=>v+(target.vad[i]*gain-v)*blend);
    this.restingMouth+=((target.restingMouth||0)*gain-this.restingMouth)*blend;
    const result={...base};if(!mouthOwned)result.ParamMouthOpenY=this.restingMouth;for(const [id,v] of Object.entries(this.current))result[id]=id.endsWith('Open')?(base[id]??1)*v:v;
    return result;
  }
}
// Cross-fades of joint angles can travel much farther than their endpoints.
// Keep the painted source rig, but bound the actual curved hand path just as
// the native player does. Opposite elbow folds pass through the resting pose.
const armIDs=['ParamShoulderL','ParamShoulderR','ParamElbowL','ParamElbowR','ParamWristL','ParamWristR','ParamBodyAngleZ','ParamTorsoLift'];
const mixArm=(a,b,f)=>Object.fromEntries(armIDs.map(id=>[id,a[id]+(b[id]-a[id])*f]));
function rotate(p,c,a){const x=p[0]-c[0],y=p[1]-c[1];return [c[0]+x*Math.cos(a)-y*Math.sin(a),c[1]+x*Math.sin(a)+y*Math.cos(a)];}
export function armAnchors(v){
  const output=[];
  for(const left of [true,false]){
    const side=left?'L':'R',s=[left?231:369,320],e=[left?173:427,418],w=[left?114:486,508],a=v['ParamShoulder'+side],out=left?a:-a;
    const key=x=>7*smooth(-.65,-.48,x)*(1-smooth(-.3,-.08,x))+20*smooth(.9,1.55,x),lo=Math.floor(out*10)/10,lift=key(lo)+(key(lo+.1)-key(lo))*(out-lo)*10;
    for(let p of [w,[w[0]+(left?-35:35),w[1]+55]]){
      p=rotate(p,w,v['ParamWrist'+side]);p=rotate(p,e,v['ParamElbow'+side]);p=rotate(p,s,a);
      p=[p[0]+12*smooth(.9,1.55,out)*(left?1:-1),p[1]-v.ParamTorsoLift-lift];
      output.push(rotate(p,[300,432],v.ParamBodyAngleZ*Math.PI/180));
    }
  }
  return output;
}
function armStep(a,b){const x=armAnchors(a),y=armAnchors(b);return Math.max(...x.map((p,i)=>Math.hypot(p[0]-y[i][0],p[1]-y[i][1])));}
function armDuration(a,b){let before=a,peak=0;for(let i=1;i<=120;i++){const after=mixArm(a,b,smooth(0,1,i/120));peak=Math.max(peak,armStep(before,after)*120);before=after;}return Math.max(.3,peak/850);}
export class ArmTransitionGuard {
  constructor(){this.last=null;this.time=null;this.pending=null;this.transition=null;}
  select(goal,rest,time){this.pending={goal,rest,time};}
  apply(target,time){
    target=Object.fromEntries(armIDs.map(id=>[id,target[id]||0]));
    if(!this.last||time<this.time){this.last=target;this.time=time;this.pending=null;return target;}
    if(this.pending){
      const {goal,rest}=this.pending,to=goal||target,from=this.last;
      const opposite=(from.ParamElbowR>.6&&to.ParamElbowR<-.15)||(from.ParamElbowR<-.15&&to.ParamElbowR>.6);
      const via=opposite&&rest?rest:null,first=via?armDuration(from,via):0;
      this.transition={from,via,first,start:time,duration:first+armDuration(via||from,to)};this.pending=null;
    }
    let result=target;
    const tr=this.transition;
    if(tr){const elapsed=time-tr.start;
      result=tr.via&&elapsed<tr.first?mixArm(tr.from,tr.via,smooth(0,tr.first,elapsed)):mixArm(tr.via||tr.from,target,smooth(0,tr.duration-tr.first,elapsed-tr.first));
      if(elapsed>=tr.duration)this.transition=null;
    }
    const dt=Math.max(0,Math.min(.1,time-this.time));
    if(dt>0&&armStep(this.last,result)>850*dt){let low=0,high=1;for(let i=0;i<16;i++){const mid=(low+high)/2;if(armStep(this.last,mixArm(this.last,result,mid))>850*dt)high=mid;else low=mid;}result=mixArm(this.last,result,low);}
    this.last=result;this.time=time;return result;
  }
}
const moodStyle={neutral:'neutral',happy:'warm',thinking:'curious',concerned:'concerned',sleepy:'sleepy'};
export class MioPerformanceController {
  static async create(model,root='Mio/') {
    const read=async path=>{const r=await fetch(root+path);if(!r.ok)throw Error('Missing '+path);return r.json();};
    const [hold,talk,encourage,profile,idle,wave]=await Promise.all([read('motions/think.motion3.json'),read('motions/talk.motion3.json'),read('motions/encourage.motion3.json'),read('Mio.emotion.json'),read('motions/idle.motion3.json'),read('motions/wave.motion3.json')]);
    return new MioPerformanceController(model,hold,talk,encourage,profile,{Idle:idle,wave,think:hold,talk,encourage});
  }
  constructor(model,hold,talk,encourage,profile,clips={}) {
    this.model=model;this.hold=hold;this.talk=talk;this.encourage=encourage;this.profile=profile;this.emotion=new EmotionMixer(profile);this.arm=new ArmTransitionGuard();this.clips=clips;this.thought=0;this.thoughtTime=null;
    this.started=performance.now()/1000;this.lastWelcome=-Infinity;this.cue=null;this.manualExpression={style:'neutral'};this.state={intent:'quiet',mood:'neutral',mouth:0};
    this.faceListener=()=>{const t=performance.now()/1000-this.started,core=model.internalModel.coreModel,attention=faceAttention(t);this.authoredRoll=core.getParameterValueById('ParamAngleZ');for(const id of ['ParamEyeLOpen','ParamEyeROpen'])core.setParameterValueById(id,1-faceBlink(t));core.setParameterValueById('ParamEyeBallX',attention[0]);core.setParameterValueById('ParamEyeBallY',attention[1]);};
    model.internalModel.on('afterMotionUpdate',this.faceListener);
    this.listener=()=>this.update();model.internalModel.on('beforeModelUpdate',this.listener);
    this.model.internalModel.motionManager.on('motionStart',this.motionListener=(group)=>{this.current=group;const sample=(clip,t)=>clip?Object.fromEntries(armIDs.map(id=>{const c=clip.Curves.find(c=>c.Id===id);return [id,c?sampleCurve(c,t):0];})):null;this.arm.select(sample(this.clips[group],group==='Idle'?0:1.25),sample(this.clips.Idle,0),performance.now()/1000);});
    this.model.expression('neutral');
  }
  event({intent='reply',mood='neutral',text='',expression=null}) {
    const now=performance.now()/1000;
    if(!['reply','quiet','waiting','welcome'].includes(intent))throw Error('Unknown intent');
    if(expression){
      expression={intensity:'normal',hand:'rest',...expression};
      if(!Object.hasOwn(this.profile.styles,expression.style)||!Object.hasOwn(this.profile.intensities,expression.intensity)||!this.profile.hands.includes(expression.hand))throw Error('Unknown semantic expression');
    }
    if(intent==='welcome'){if(now-this.lastWelcome<180)intent='reply';else this.lastWelcome=now;}
    if(intent==='reply'&&expression?.hand==='wave'){if(now-this.lastWelcome<180)expression={...expression,hand:'rest'};else this.lastWelcome=now;}
    this.cue={intent,mood,text,expression,started:now,speech:new SpeechTimeline(text),phase:'',restored:false};
    this.model.expression('neutral');this.model.motion('Idle',0,3);this.state={intent,mood,mouth:0};
  }
  respond(decision,text){this.event({intent:['none','focus'].includes(decision.reaction)?'quiet':decision.reaction==='greet'?'welcome':'reply',mood:decision.mood,text,expression:decision.expression});}
  setMood(mood){const style=moodStyle[mood]||mood;if(!Object.hasOwn(this.profile.styles,style))throw Error('Unknown expression');this.cue=null;this.manualExpression={style};this.model.expression('neutral');this.state={intent:'manual-expression',mood,mouth:0};}
  manual(group){this.cue=null;this.state={intent:'manual',mood:this.manualExpression.style,phase:group,mouth:0};return this.model.motion(group,0,3);}
  update(){
    const core=this.model.internalModel.coreModel,clock=performance.now()/1000-this.started;
    // Pixi 0.4 adds pointer X*Y to roll and a separate breathing roll after
    // motion playback. Keep the authored gesture tilt; pointer attention owns
    // yaw/pitch instead. Held source poses below may still set their own tilt.
    core.setParameterValueById('ParamAngleZ',this.authoredRoll??0);
    let expression=this.manualExpression;
    if(this.cue){
      const c=this.cue,t=performance.now()/1000-c.started,st=t-(c.intent==='welcome'?.35:0);
      const speaking=!['quiet','waiting'].includes(c.intent)&&st>=0&&st<c.speech.duration;
      let phase=c.intent==='welcome'&&t<4.4?'wave':c.intent==='waiting'&&t>.55?'think':c.intent==='reply'&&speaking&&Array.from(c.text).length>16?'talk':'Idle';
      if(c.expression&&c.intent==='reply'&&t<Math.max(3.6,c.speech.duration))phase={rest:'Idle',wave:t<5?'wave':'Idle',explain:'talk',chin:'think',encourage:'encourage'}[c.expression.hand];
      if(phase!==c.phase){c.phase=phase;c.phaseStarted=t;this.model.motion(phase,0,3);}
      const local=t-c.phaseStarted;
      if((phase==='think'&&local>2.2)||(['talk','encourage'].includes(phase)&&local>3.8)){
        for(const curve of (phase==='think'?this.hold:phase==='encourage'?this.encourage:this.talk).Curves)if(curve.Target==='Parameter'&&!Object.hasOwn(this.profile.styles.neutral.face,curve.Id)&&!['ParamHairFront','ParamHairBack','ParamMouthOpenY','ParamEyeBallX','ParamEyeBallY'].includes(curve.Id))core.setParameterValueById(curve.Id,sampleCurve(curve,phase==='think'?2.2:3.8));
      }
      const mouth=speaking?c.speech.mouth(st):0;core.setParameterValueById('ParamMouthOpenY',mouth);
      c.restored=c.intent!=='waiting'&&t>Math.max(3.6,c.speech.duration)+2;
      expression=c.restored?{style:'neutral'}:(c.expression||{style:moodStyle[c.mood]||'neutral'});
      this.state={intent:c.intent,mood:c.restored?'neutral':c.mood,expression,mouth,phase,speaking,elapsed:t};
    }
    // Ownership is applied after the player's motion, blink, expression and
    // physics layers. Speech and authored manual talk retain mouth aperture;
    // silent expression previews may use their authored resting mouth.
    const blink=1-faceBlink(clock),values=this.emotion.apply({ParamEyeLOpen:blink,ParamEyeROpen:blink},expression,clock,!!this.cue||this.current==='talk');
    for(const [id,value] of Object.entries(values))core.setParameterValueById(id,value);
    const desired=Object.fromEntries(armIDs.map(id=>[id,core.getParameterValueById(id)])),guarded=this.arm.apply(desired,performance.now()/1000);
    for(const [id,value] of Object.entries(guarded))core.setParameterValueById(id,value);
    const thoughtTarget=armStep(desired,guarded)>3?0:core.getParameterValueById('ParamThought'),thoughtStep=Math.max(0,Math.min(.1,clock-(this.thoughtTime??clock)))*4;
    this.thoughtTime=clock;this.thought=Math.max(this.thought-thoughtStep,Math.min(this.thought+thoughtStep,thoughtTarget));core.setParameterValueById('ParamThought',this.thought);
    for(const id of ['ParamHandL','ParamHandR'])core.setParameterValueById(id,Math.round(core.getParameterValueById(id)));
    // The source owns chest perspective and joint attachment. Here we only
    // couple the standard body parameter to the final horizontal attention.
    core.setParameterValueById('ParamBodyAngleX',Math.max(-30,Math.min(30,core.getParameterValueById('ParamAngleX')))*.2);
  }
  destroy(){this.model.internalModel.off('afterMotionUpdate',this.faceListener);this.model.internalModel.off('beforeModelUpdate',this.listener);this.model.internalModel.motionManager.off('motionStart',this.motionListener);}
}
