#!/usr/bin/env python3
"""Add live telemetry to the pinned upstream, preserving inference and capture scheduling."""
import argparse
from pathlib import Path
import shutil
import subprocess

parser = argparse.ArgumentParser()
parser.add_argument('checkout', type=Path)
parser.add_argument('--replace-owned-patches', action='store_true', help='Migrate this experiment\'s earlier telemetry patches')
args = parser.parse_args()
revision = '0d4caa1fd36d2581785efa80e6ade09983a18f05'
header = '// Generated by Harumachi prepare_live.py from ' + revision + '.\n'
if subprocess.check_output(['git', '-C', str(args.checkout), 'rev-parse', 'HEAD'], text=True).strip() != revision:
    raise SystemExit('Upstream revision differs; inspect before adapting telemetry.')

patches = {
    'ApplicationDelegate.swift': [('Task { await model.initialize() }',
        'Task { await model.initialize(); if LiveTrial.active { await LiveTrial.run(model: model, controls: window) } }')],
    'AppModel.swift': [
        ('let result = try await engine.process(captured, settings: settings)',
         'LiveMetrics.shared.received(captured)\n                        let result = try await engine.process(captured, settings: settings)'),
        ('frame = result; dropped = receiver.frames.dropped',
         'LiveMetrics.shared.processed(result, dropped: receiver.frames.dropped)\n        frame = result; dropped = receiver.frames.dropped')],
    'ScreenCapture.swift': [
        ('config.capturesAudio = true', 'config.capturesAudio = !LiveTrial.active'),
        ('$0.windowLayer == 0 && $0.frame.width > 100',
         '($0.windowLayer == 0 || (LiveTrial.active && ($0.title ?? "").hasPrefix("Harumachi Neural Live Trial"))) && $0.frame.width > 100')],
    'MetalPreview.swift': [
        ('private var pixels: CVPixelBuffer?', 'private var pixels: CVPixelBuffer?\n    var measurementSource: Double?'),
        ('view.colorPixelFormat = .bgra8Unorm', 'if LiveTrial.active { view.wantsLayer = true }\n        view.colorPixelFormat = .bgra8Unorm'),
        ('context.coordinator.display(frame?.pixels)',
         'context.coordinator.measurementSource = LiveTrial.active ? frame?.capturedAt : nil; context.coordinator.display(frame?.pixels)'),
        ('panel.level = .floating', 'panel.level = LiveTrial.active ? NSWindow.Level(rawValue: NSWindow.Level.statusBar.rawValue + 1) : .floating'),
        ('panel.isOpaque = true; panel.hasShadow = false; panel.ignoresMouseEvents = true', '''panel.isOpaque = !LiveTrial.active
        // Fractional translucency keeps the underlying Godot window rendering.
        if LiveTrial.active { panel.backgroundColor = .clear; panel.alphaValue = 0.999 }
        panel.hasShadow = false; panel.ignoresMouseEvents = true'''),
        ('''panel.setFrame(NSRect(x: bounds.minX, y: desktopTop - bounds.maxY,
                              width: bounds.width, height: bounds.height), display: true)''',
         '''let target = NSRect(x: bounds.minX, y: desktopTop - bounds.maxY, width: bounds.width, height: bounds.height)
        if !NSEqualRects(panel.frame, target) { panel.setFrame(target, display: false) }'''),
        ('renderer.display(frame.pixels); panel.orderFrontRegardless()', '''renderer.measurementSource = LiveTrial.active ? frame.capturedAt : nil
        renderer.display(frame.pixels)
        if !panel.isVisible { panel.orderFrontRegardless() }
        CATransaction.flush()'''),
        ('encoder.endEncoding(); command.present(drawable)', '''encoder.endEncoding()
        if let source = measurementSource {
            let submitted = ProcessInfo.processInfo.systemUptime
            let presentedWindow = Double(view.window?.windowNumber ?? -1)
            LiveMetrics.shared.submitted(source: source, host: submitted)
            command.addCompletedHandler { completed in
                LiveMetrics.shared.completed(source: source, gpuEnd: completed.gpuEndTime)
            }
            drawable.addPresentedHandler { shown in
                LiveMetrics.shared.presented(source: source, host: shown.presentedTime, submitted: submitted, window: presentedWindow)
            }
        }
        command.present(drawable)''')]
}
prepared = {}
for name, replacements in patches.items():
    relative = 'Sources/NeuralScreenMac/' + name
    original = subprocess.check_output(['git', '-C', str(args.checkout), 'show', revision + ':' + relative], text=True)
    current = (args.checkout / relative).read_text()
    text = original
    for before, after in replacements:
        if text.count(before) != 1:
            raise SystemExit(f'{name}: upstream anchor changed')
        text = text.replace(before, after, 1)
    output = header + text
    owned_migration = args.replace_owned_patches and ('LiveTrial' in current or 'LiveMetrics' in current)
    if current not in (original, output) and not owned_migration:
        raise SystemExit(f'{name}: existing edits; refusing to overwrite')
    prepared[args.checkout / relative] = output
for path, text in prepared.items():
    path.write_text(text)
for name in ['LiveTrial.swift', 'VisibleProbe.swift']:
    shutil.copyfile(Path(__file__).with_name(name), args.checkout / 'Sources/NeuralScreenMac' / name)
print('Live telemetry installed; inference and capture scheduling unchanged.')
