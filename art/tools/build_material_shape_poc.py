"""Author editable tree crowns and curved grass for the opt-in material POC.

Run with Blender --background --python this.py -- --pass 8.
The rejected bakery replacement is built only with --experimental-bakery-source.
Earlier pass switches are development aids; exact earlier sources live with their evidence.
Original game GLBs are read-only. Branch layout, seed, UVs and normals are authored
here and exported to source .blend and candidate GLB, not generated by the game.
"""
from pathlib import Path
import argparse
import hashlib
import json
import math
import random
import sys

import bpy
import bmesh
from mathutils import Vector

ROOT = Path(__file__).resolve().parents[2]
DEST = ROOT / "game/assets/material_light_poc/shape"
AUTHOR = ROOT / "art/library/material_shape_poc_20261025/authoring"
TREES = ["T01_courtyard_tree", "T02_summer_tree", "T03_round_ginkgo", "T04_slender_cedar"]
STYLES = {"backdrop": (.14, .34, .25), "plaza": (.08, .22, .15),
          "lawn": (.12, .28, .24), "meadow": (.18, .42, .30), "tall": (.45, .9, .32)}


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def mesh_object(name, vertices, faces, uvs=None, normals=None, colours=None):
    mesh = bpy.data.meshes.new(name)
    mesh.from_pydata(vertices, [], faces)
    mesh.update()
    obj = bpy.data.objects.new(name, mesh)
    bpy.context.collection.objects.link(obj)
    if uvs:
        uv = mesh.uv_layers.new(name="UVMap")
        for loop in mesh.loops:
            uv.data[loop.index].uv = uvs[loop.vertex_index]
    if normals:
        for face in mesh.polygons:
            face.use_smooth = True
        mesh.normals_split_custom_set_from_vertices(normals)
    if colours:
        col = mesh.color_attributes.new(name="Col", type="FLOAT_COLOR", domain="POINT")
        for i, value in enumerate(colours):
            col.data[i].color = value
    return obj


def painted_material(name, texture):
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    principled = mat.node_tree.nodes.get("Principled BSDF")
    principled.inputs['Roughness'].default_value = 1
    tex = mat.node_tree.nodes.new("ShaderNodeTexImage")
    tex.image = bpy.data.images.load(str(texture), check_existing=True)
    mat.node_tree.links.new(tex.outputs['Color'], principled.inputs['Base Color'])
    mat.node_tree.links.new(tex.outputs['Alpha'], principled.inputs['Alpha'])
    mat.surface_render_method = 'DITHERED'
    return mat


def export(name):
    # The authoring file keeps textures; the runtime binds shared candidate textures
    # explicitly, so the GLB need not embed four duplicate copies of the atlas.
    bpy.context.preferences.filepaths.save_version = 0
    bpy.ops.file.pack_all()
    bpy.ops.wm.save_as_mainfile(filepath=str(AUTHOR / (name + '.blend')))
    placeholder = bpy.data.materials.new('POC runtime material binding')
    placeholder.diffuse_color = (.25,.35,.15,1)
    for obj in bpy.context.scene.objects:
        if obj.type != 'MESH': continue
        for index in range(len(obj.data.materials)): obj.data.materials[index] = placeholder
        if not obj.data.materials: obj.data.materials.append(placeholder)
    bpy.ops.export_scene.gltf(filepath=str(DEST / (name + '.glb')), export_format='GLB',
                             export_yup=True, export_apply=True, export_materials='EXPORT',
                             export_animations=False, export_normals=True,
                             export_vertex_color='ACTIVE',export_all_vertex_colors=True)


def tree(name, iteration):
    rng = random.Random(261025 + TREES.index(name) * 379)
    bpy.ops.wm.read_factory_settings(use_empty=True)
    source = ROOT / 'game/assets/models' / (name + '.glb')
    bpy.ops.import_scene.gltf(filepath=str(source))
    foliage = next(o for o in bpy.context.scene.objects if o.type == 'MESH' and o.name.startswith('Foliage'))
    old_name = foliage.name
    points = [foliage.matrix_world @ Vector(p) for p in foliage.bound_box]
    low = Vector([min(p[i] for p in points) for i in range(3)])
    high = Vector([max(p[i] for p in points) for i in range(3)])
    centre = (low + high) / 2
    radius = (high - low) / 2
    original_vertices = len(foliage.data.vertices)
    bpy.data.objects.remove(foliage, do_unlink=True)
    verts, faces, uv, normals, colours = [], [], [], [], []
    clusters = []
    cedar = name.startswith('T04')
    if cedar and iteration >= 6:
        for branch in range(27):
            t = branch/27
            angle = branch*2.399963
            reach = radius.x*(1-t)**.64*.42
            clusters.append((Vector((math.cos(angle)*reach,math.sin(angle)*reach,
                                    low.z+.45+t*(high.z-low.z-.65))),
                             Vector((radius.x*(1-t)*.54+.20,radius.y*(1-t)*.54+.20,.68))))
    elif cedar:
        for branch in range(22):
            t = branch / 22
            angle = branch * 2.399963
            reach = radius.x * (1 - t) ** .65 * rng.uniform(.55, .83)
            clusters.append((Vector((math.cos(angle)*reach, math.sin(angle)*reach,
                                    low.z + .6 + t*(high.z-low.z-.8))),
                             Vector((.72*(1-t)+.22, .65*(1-t)+.2, .48))))
    else:
        count = 17 if name.startswith('T01') else 21
        for branch in range(count):
            t = (branch + .4) / count
            angle = branch * 2.399963 + .2
            reach = math.sin(math.pi*t)**.75
            z = low.z + radius.z * ((.20 + 1.55*t) if iteration >= 6 else (.48 + 1.32*t))
            horizontal = Vector((math.cos(angle), math.sin(angle), 0))
            position = centre.copy()
            position.x += horizontal.x*radius.x*reach*.60
            position.y += horizontal.y*radius.y*reach*.60
            position.z = z
            size = Vector((radius.x*.40, radius.y*.39, radius.z*.26)) * rng.uniform(.85,1.14)
            if iteration >= 6: size *= 1.16
            clusters.append((position,size))
    for cluster_id, (origin, size) in enumerate(clusters):
        cluster_normal=Vector(((origin.x-centre.x)/radius.x,(origin.y-centre.y)/radius.y,(origin.z-centre.z)/radius.z+.8)).normalized()
        if iteration >= 7:
            # A low-frequency inner volume remains readable beyond leaf-card scale.
            core=bmesh.new();bmesh.ops.create_icosphere(core,subdivisions=2,radius=1)
            core.verts.ensure_lookup_table();core.faces.ensure_lookup_table()
            first=len(verts)
            for v in core.verts:
                d=v.co.normalized();scale=.72*(1+.08*math.sin(d.x*7+d.y*9+d.z*5))
                point=origin+Vector((d.x*size.x,d.y*size.y,d.z*size.z))*scale
                verts.append(tuple(point));uv.append((-1,0))
                normals.append(tuple((cluster_normal*.76+d*.24).normalized()))
                colours.append((.92,.92,.92,0))
            for f in core.faces:faces.append(tuple(first+v.index for v in f.verts))
            core.free()
        count = (18 if cedar else 22) if iteration >= 6 else (30 if cedar else 34)
        if iteration >= 7: count=16
        for leaf in range(count):
            # Fibonacci shell plus interior branches: leaf groups have real volume
            # and different silhouettes from the front and side.
            z = 1 - 2*(leaf+.5)/count
            angle = leaf*2.399963 + cluster_id*.65
            d = Vector((math.sqrt(1-z*z)*math.cos(angle),math.sqrt(1-z*z)*math.sin(angle),z))
            position = origin + Vector((d.x*size.x,d.y*size.y,d.z*size.z))*rng.uniform(.60,1.0)
            facing = (d + Vector((rng.uniform(-.3,.3),rng.uniform(-.3,.3),.22))).normalized()
            right = facing.cross(Vector((0,0,1)))
            if right.length < .01: right = Vector((1,0,0))
            right.normalize();up = facing.cross(right).normalized()
            width = rng.uniform(.45,.68) if cedar else rng.uniform(.52,.86)
            if iteration >= 6: width *= 1.8
            # The uppermost leaves taper; silhouette stays irregular rather than
            # becoming a cone made from a continuous shell.
            if cedar: width *= .7+.3*(1-cluster_id/len(clusters))
            first = len(verts);cell = rng.randrange(4)
            tint = rng.uniform(.78,1.0)
            if iteration >= 7:tint=.90+.04*math.sin(cluster_id*2.3)+rng.uniform(-.02,.02)
            for yy,xx in [(0,0),(0,1),(1,1),(1,0)]:
                point = position+right*(xx-.5)*width+up*(yy-.5)*width
                verts.append(tuple(point))
                uv.append(((cell%2+xx)*.5,(cell//2+yy)*.5))
                radial = Vector(((point.x-origin.x)/max(size.x,.1),(point.y-origin.y)/max(size.y,.1),(point.z-origin.z)/max(size.z,.1)))
                normal = (radial*.65 + Vector((0,0,.65))).normalized()
                if iteration >= 7:normal=(cluster_normal*.8+normal*.2).normalized()
                normals.append(tuple(normal));colours.append((tint,tint,tint,1))
            faces.extend([(first,first+1,first+2),(first,first+2,first+3)])
    obj = mesh_object(old_name,verts,faces,uv,normals,colours)
    texture = DEST/('cedar_atlas.png' if cedar else 'leaf_atlas.png')
    obj.data.materials.append(painted_material('POC painted cedar' if cedar else 'POC painted broadleaf',texture))
    export(name)
    return {'id':name,'source_sha256':sha(source),'candidate_sha256':sha(DEST/(name+'.glb')),
            'foliage_part':old_name,'original_vertices':original_vertices,'vertices':len(verts),
            'triangles':len(faces),'leaf_sprays':len(clusters)*count,'crown_groups':len(clusters),'inner_crown_volumes':len(clusters) if iteration>=7 else 0,
            'trunk':'retained without geometry edits','seed':261025+TREES.index(name)*379}


def grass(iteration):
    bpy.ops.wm.read_factory_settings(use_empty=True)
    report=[]
    for style,(h0,h1,radius) in STYLES.items():
        for variant in range(3):
            rng=random.Random(1083+len(style)*317+variant*17)
            verts,faces,uv,normals,colours=[],[],[],[],[]
            blade_count=50 if iteration>=7 else 19
            for blade in range(blade_count):
                ang=rng.random()*math.tau
                distance=math.sqrt(rng.random())*radius
                root=Vector((math.cos(ang)*distance,math.sin(ang)*distance,0))
                direction=Vector((math.cos(ang+.4),math.sin(ang+.4),0))
                side=Vector((-direction.y,direction.x,0))
                height=rng.uniform(h0,h1);width=rng.uniform(.022,.038) if iteration >= 6 else rng.uniform(.012,.025)
                short=iteration>=7 and blade>=19
                if iteration>=7:
                    height*=.78 if style in ('lawn','plaza','backdrop') else .9
                    width*=1.14
                if short:height=rng.uniform(.045,.11);width=rng.uniform(.028,.044)
                if iteration>=8 and not short:
                    # Taller, broader accent tufts on a low sward, instead of one height.
                    height*=1.30 if variant==2 else .78
                    width*=1.12 if variant==2 else 1.
                lean=height*rng.uniform(.28,.70)
                colour=(rng.random(),rng.random(),0,1)
                start=len(verts)
                levels=[0,.2,.4,.6,.8,1.]
                if short:levels=[0,.5,1.]
                for t in levels:
                    mid=root+direction*(lean*t*t)+Vector((0,0,height*(t-.22*t*t*t)))
                    width_t=width*.5*max(0,1-t)**.75
                    for edge in [-1,0,1]:
                        point=mid+side*width_t*edge+Vector((0,0,(1-abs(edge))*width_t*.23))
                        # glTF flips Blender's V: Godot must receive 0 at the root.
                        verts.append(tuple(point));uv.append(((edge+1)*.5,1-t if iteration >= 6 else t));colours.append(colour)
                        n=(Vector((0,0,1))*.88+side*edge*.12).normalized();normals.append(tuple(n))
                for seg in range(len(levels)-1):
                    for side_index in range(2):
                        a=start+seg*3+side_index;b=a+1;c=a+4;d=a+3
                        if seg==len(levels)-2:faces.append((a,b,c))
                        else:faces.extend([(a,b,c),(a,c,d)])
            name=f'Grass_{style}_{variant}'
            mesh_object(name,verts,faces,uv,normals,colours)
            report.append({'name':name,'blades':blade_count,'short_blades':31 if iteration>=7 else 0,'vertices':len(verts),'triangles':len(faces),'main_width_m':[.02508,.04332] if iteration>=7 else ([.022,.038] if iteration>=6 else [.012,.025]), 'godot_root_v':0 if iteration>=6 else 1})
    export('Grass_curved')
    return report


def main():
    args=sys.argv[sys.argv.index('--')+1:] if '--' in sys.argv else []
    parser=argparse.ArgumentParser();parser.add_argument('--pass',dest='iteration',type=int,default=8,choices=range(5,9))
    parser.add_argument('--experimental-bakery-source',action='store_true',help='Rebuild the rejected architecture experiment; default preserves the original bakery')
    options=parser.parse_args(args)
    DEST.mkdir(parents=True,exist_ok=True);AUTHOR.mkdir(parents=True,exist_ok=True)
    trees=[tree(name,options.iteration) for name in TREES]
    grasses=grass(options.iteration)
    architecture = None
    architecture_enabled=options.iteration>=6 and options.experimental_bakery_source
    if architecture_enabled:
        sys.path.insert(0,str(Path(__file__).resolve().parent))
        from material_shape_bakery import build_bakery
        architecture=build_bakery(ROOT,DEST,AUTHOR,options.iteration)
        architecture.update(source_sha256=sha(ROOT/'game/assets/models/S02.glb'),candidate_sha256=sha(DEST/'S02_refined.glb'))
    report={'iteration':options.iteration,'blender':bpy.app.version_string,'generator':str(Path(__file__).relative_to(ROOT)),
            'scope':'candidate source assets, not production integration','trees':trees,'grass':grasses,
            'atlas_sha256':sha(DEST/'leaf_atlas.png'),'cedar_atlas_sha256':sha(DEST/'cedar_atlas.png'),'architecture':architecture,
            'architecture_active':architecture_enabled,'bakery_source_sha256':sha(ROOT/'game/assets/models/S02.glb')}
    (ROOT/'art/manifests/material_shape_poc_20261025.json').write_text(json.dumps(report,indent=2)+'\n')
    (DEST/'config.json').write_text(json.dumps({'iteration':options.iteration,'architecture':architecture_enabled,'bakery_source_required':not architecture_enabled},indent=2)+'\n')


if __name__=='__main__':main()
